#Кол во дней
days_in_month = {
    1: 31,   # январь
    2: 28,   # февраль (невисокосный год)
    3: 31,   # март
    4: 30,   # апрель
    5: 31,   # май
    6: 30,   # июнь
    7: 31,   # июль
    8: 31,   # авг
    9: 30,   # сентябрь
    10: 31,  # октябрь
    11: 30,  # ноябрь
    12: 31,  # декабрь
}
def get_days(month):
    return days_in_month[month]
month=int(input())
print(get_days(month))

import pytest,playwright
from playwright.sync_api import Page, expect
base_url='https://www.globalsqa.com/angularJs-protractor/BankingProject/#/login'

def test_login_button(page:Page):
    page.goto(base_url)
    expect(page.get_by_role('button', name='Customer Login', exact= True)).to_be_visible()
    expect(page.get_by_role('button', name='Customer Login', exact= True)).to_be_enabled()
    expect(page.get_by_role('button', name='Bank Manager Login',exact=True)).to_be_visible()
    expect(page.get_by_role('button', name='Bank Manager Login',exact=True)).to_be_enabled()
def test_customer_selection(page: Page):
    page.goto(base_url)
    page.get_by_role('button', name='Customer Login', exact=True)

    get_name = page.locator("#userSelect")
    
    get_name.select_option('Harry Potter')
    expect(get_name).to_be_visible()
    expect(page.get_by_role('button', name='Login', exact=True)).to_be_enabled()
    expect(page.get_by_role('button', name='Login', exact=True)).to_be_visible()
def test_login_as_customer(page :Page):
    page.goto(base_url)
    page.get_by_role('button', name='Customer Login', exact=True).click()
    page.locator("#userSelect").select_option('Harry Potter') 
    page.get_by_role('button', name='Login', exact=True).click()
    expect(page.get_by_text('Harry Potter')).to_be_visible()
    expect(page.get_by_role('button', name='Logout', exact=True)).to_be_visible()
    expect(page.get_by_role('button', name='Transactions',exact=True)).to_be_visible()
    expect(page.get_by_role('button', name='Deposit',exact=True)).to_be_visible()
    expect(page.get_by_role('button', name='Withdrawl',exact=True)).to_be_visible()
def test_logout_as_customer(page :Page):
    page.goto(base_url)
    page.get_by_role('button', name='Customer Login', exact=True).click()
    page.locator("#userSelect").select_option('Harry Potter') 
    page.get_by_role('button', name='Login', exact=True).click()
    button_logout=page.get_by_role('button', name='Logout', exact=True)
    button_logout.click()
    expect(button_logout).to_be_hidden()
    expect(page.locator("#userSelect")).to_be_visible()
def test_change_deposit_amount(page :Page):
    page.goto(base_url)
    page.get_by_role('button', name='Customer Login', exact=True).click()
    page.locator("#userSelect").select_option('Harry Potter') 
    page.get_by_role('button', name='Login', exact=True).click()
    page.get_by_role('button', name='Deposit',exact=True).click()
    amount=page.get_by_placeholder('amount')
    amount.fill('100')
    expect(amount).to_have_value('100')
    amount.fill('250')
    expect(amount).to_have_value('250')
@pytest.mark.parametrize('dep',['10','50','200'])
def test_deposit_amounts(page: Page, dep):
    page.goto(base_url)
    page.get_by_role('button', name='Customer Login', exact=True).click()
    page.locator("#userSelect").select_option('Harry Potter') 
    page.get_by_role('button', name='Login', exact=True).click()
    page.get_by_role('button', name='Deposit',exact=True).click()
    amount=page.get_by_placeholder('amount')
    amount.fill(dep)
    amount.press('Enter')
    expect(page.get_by_text('Deposit Successful')).to_be_visible()
